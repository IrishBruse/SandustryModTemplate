#!/usr/bin/env node
/**
 * Compile Tailwind utilities for docs/ui/canvas preview.html pages.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileTailwindUtilities } from "../build/compile-tailwind.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const CANVAS = join(ROOT, "docs/ui/canvas");
const OUT = join(CANVAS, "_preview/utilities.css");

export async function writePreviewUtilities() {
  const css = await compileTailwindUtilities([
    join(ROOT, "framework/ui/**/*.{ts,tsx}"),
    join(CANVAS, "**/*.html"),
  ]);
  writeFileSync(OUT, `/* Generated by scripts/ui/compile-preview-css.mjs. Do not edit. */\n${css}`);
  return { css: OUT };
}

const thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] && thisFile === process.argv[1]) {
  const out = await writePreviewUtilities();
  console.log(`wrote ${out.css}`);
}
