#!/usr/bin/env node
/**
 * Screenshot each [data-ui-preview] block from framework/ui preview pages
 * using agent-browser. Writes PNGs next to preview.html.
 */
import { createServer } from "node:http";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../framework/ui");
const PORT = 4173;
const SESSION = "sandustry-ui-previews";
const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".png": "image/png",
  ".js": "text/javascript; charset=utf-8",
};

function contentType(path) {
  const ext = path.slice(path.lastIndexOf("."));
  return MIME[ext] ?? "application/octet-stream";
}

function findPreviewPages(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules") continue;
    const path = join(dir, name);
    if (!statSync(path).isDirectory()) continue;
    if (name === "_preview" || name === "shared") {
      if (name === "_preview") continue;
      continue;
    }
    const preview = join(path, "preview.html");
    if (existsSync(preview)) acc.push(preview);
    findPreviewPages(path, acc);
  }
  return acc;
}

function previewNames(htmlPath) {
  const html = readFileSync(htmlPath, "utf8");
  return [...html.matchAll(/data-ui-preview="([^"]+)"/g)].map((match) => match[1]);
}

async function runAgent(args) {
  await execFileAsync("agent-browser", ["--session", SESSION, ...args], {
    stdio: "inherit",
  });
}

function startServer() {
  return new Promise((resolve) => {
    const server = createServer((req, res) => {
      const urlPath = decodeURIComponent((req.url ?? "/").split("?")[0]);
      const filePath = join(ROOT, urlPath);
      if (!filePath.startsWith(ROOT) || !existsSync(filePath) || statSync(filePath).isDirectory()) {
        res.writeHead(404);
        res.end("Not found");
        return;
      }
      try {
        res.writeHead(200, { "Content-Type": contentType(filePath) });
        res.end(readFileSync(filePath));
      } catch (error) {
        res.writeHead(500);
        res.end(String(error));
      }
    });
    server.listen(PORT, "127.0.0.1", () => resolve(server));
  });
}

function writeGallery(entries) {
  const rows = entries
    .map(
      ({ folder, name, imageRel }) => `
        <section class="card">
          <h2>${folder}/${name}</h2>
          <img src="${imageRel}" alt="${name}" />
          <p><a href="../${folder}/preview.html">Open preview.html</a></p>
        </section>`,
    )
    .join("\n");

  writeFileSync(
    join(ROOT, "_preview/gallery.html"),
    `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>framework/ui gallery</title>
  <style>
    body { background: #0f172a; color: #e2e8f0; font-family: monospace; margin: 0; padding: 24px; }
    h1 { font-size: 18px; margin: 0 0 24px; }
    .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(280px, 1fr)); gap: 20px; }
    .card { background: #1e293b; border: 1px solid #334155; border-radius: 8px; padding: 16px; }
    .card h2 { font-size: 12px; color: #94a3b8; margin: 0 0 12px; text-transform: uppercase; letter-spacing: 0.08em; }
    img { max-width: 100%; background: #1a2332; border-radius: 4px; border: 1px solid #334155; }
    a { color: #ffe700; }
  </style>
</head>
<body>
  <h1>framework/ui component previews</h1>
  <p style="color:#94a3b8;margin-top:-12px;margin-bottom:24px">Generated by <code>npm run ui:previews</code></p>
  <div class="grid">${rows}
  </div>
</body>
</html>`,
  );
}

const previews = findPreviewPages(ROOT);
if (previews.length === 0) {
  console.error("No preview.html files found under framework/ui");
  process.exit(1);
}

const server = await startServer();
const gallery = [];

try {
  await runAgent(["close", "--all"]);
} catch {
  // No open session yet.
}

for (const htmlPath of previews) {
  const folder = relative(ROOT, dirname(htmlPath));
  const url = `http://127.0.0.1:${PORT}/${folder}/preview.html`;
  console.log(`\n${folder}/preview.html`);

  await runAgent(["open", url]);
  await runAgent(["wait", "--load", "domcontentloaded"]);
  await runAgent(["wait", "1000"]);
  await runAgent(["set", "viewport", "800", "600", "1"]);

  for (const name of previewNames(htmlPath)) {
    const outPath = join(dirname(htmlPath), `${name}.png`);
    const selector = `[data-ui-preview=${name}]`;
    console.log(`  screenshot ${name} -> ${relative(ROOT, outPath)}`);
    await runAgent(["screenshot", selector, outPath]);
    gallery.push({
      folder,
      name,
      imageRel: `../${folder}/${name}.png`,
    });
  }
}

writeGallery(gallery);
console.log(`\nGallery: framework/ui/_preview/gallery.html (${gallery.length} images)`);

await runAgent(["close"]);
server.close();
